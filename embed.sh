#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# embed.sh — OPTIONAL. Bundles the artwork image into js/artwork-embed.js as a
# data URI, so the piece also runs by double-clicking index.html offline (no
# server). Not needed for GitHub Pages / any http host — the app loads
# assets/artwork.png directly there.
#
#   ./embed.sh                 # embeds assets/artwork.png
#   ./embed.sh path/to/img.png # embeds a specific image
#
# Requires macOS `sips` (preinstalled) + `base64`.
# ---------------------------------------------------------------------------
set -e
cd "$(dirname "$0")"

SRC="${1:-assets/artwork.jpg}"
[ -f "$SRC" ] || { echo "not found: $SRC"; exit 1; }

TMP="$(mktemp -d)"
# downsample to max 1000px, JPEG q82 — plenty for sampling, keeps the file small
sips -Z 1000 -s format jpeg -s formatOptions 82 "$SRC" --out "$TMP/a.jpg" >/dev/null

{
  printf '/* auto-generated by embed.sh — the artwork image as a data URI. */\n'
  printf 'window.WOVEN_IMAGE = "data:image/jpeg;base64,'
  base64 < "$TMP/a.jpg" | tr -d '\n'
  printf '";\n'
} > js/artwork-embed.js

rm -rf "$TMP"
echo "wrote js/artwork-embed.js ($(wc -c < js/artwork-embed.js | tr -d ' ') bytes) from $SRC"
echo "index.html already includes it — the piece now runs offline too."
